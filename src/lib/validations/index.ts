import { z } from "zod";

export const vehicleSchema = z.object({
  stockNumber: z.string().min(2, "Stock number is required"),
  registrationNumber: z.string().optional().nullable(),
  vin: z.string().optional().nullable(),
  make: z.string().min(1, "Make is required"),
  model: z.string().min(1, "Model is required"),
  variant: z.string().optional().nullable(),
  year: z.coerce.number().int().min(1980).max(2030),
  color: z.string().min(1, "Color is required"),
  mileage: z.coerce.number().int().min(0),
  fuelType: z.string().min(1, "Fuel type is required"),
  transmission: z.string().min(1, "Transmission is required"),
  bodyType: z.string().min(1, "Body type is required"),
  status: z.enum([
    "AVAILABLE",
    "RESERVED",
    "SOLD",
    "PENDING_ACQUISITION",
    "IN_TRANSIT",
    "ARCHIVED",
  ]).default("AVAILABLE"),
  location: z.string().default("Ngong Road Showroom (HQ)"),
  purchasePrice: z.coerce.number().min(0, "Purchase price must be >= 0"),
  askingPrice: z.coerce.number().min(0, "Asking price must be >= 0"),
  minimumPrice: z.coerce.number().min(0, "Minimum price must be >= 0"),
  supplierId: z.string().optional().nullable(),
  dateAcquired: z.string().optional(),
  notes: z.string().optional().nullable(),
});

export const expenseSchema = z.object({
  vehicleId: z.string().min(1, "Vehicle is required"),
  category: z.enum([
    "PURCHASE",
    "TRANSPORT",
    "REPAIRS",
    "DETAILING",
    "INSPECTION",
    "REGISTRATION",
    "INSURANCE",
    "ADVERTISING",
    "OTHER",
  ]),
  description: z.string().min(2, "Description is required"),
  amount: z.coerce.number().positive("Amount in KSh. must be greater than 0"),
  incurredAt: z.string().optional(),
});

export const customerSchema = z.object({
  fullName: z.string().min(2, "Customer full name is required"),
  phone: z.string().min(7, "Phone number is required"),
  altPhone: z.string().optional().nullable(),
  email: z.string().email().optional().or(z.literal("")),
  address: z.string().optional().nullable(),
  location: z.string().optional().nullable(),
  idPassportNo: z.string().optional().nullable(),
  customerType: z.enum(["INDIVIDUAL", "COMPANY", "DEALER", "FLEET"]).default("INDIVIDUAL"),
  preferredMakes: z.string().optional().nullable(),
  preferredModels: z.string().optional().nullable(),
  budgetMin: z.coerce.number().optional().nullable(),
  budgetMax: z.coerce.number().optional().nullable(),
  preferredYear: z.coerce.number().optional().nullable(),
  preferredFuel: z.string().optional().nullable(),
  preferredTrans: z.string().optional().nullable(),
  preferredBody: z.string().optional().nullable(),
  assignedToId: z.string().optional().nullable(),
  notes: z.string().optional().nullable(),
});

export const leadSchema = z.object({
  customerId: z.string().min(1, "Customer is required"),
  vehicleId: z.string().optional().nullable(),
  source: z.enum([
    "WALK_IN",
    "WEBSITE",
    "INSTAGRAM",
    "FACEBOOK",
    "WHATSAPP",
    "PHONE",
    "REFERRAL",
    "DEALER",
    "MARKETPLACE",
    "OTHER",
  ]).default("WALK_IN"),
  assignedToId: z.string().optional().nullable(),
  budget: z.coerce.number().optional().nullable(),
  expectedPurchaseDate: z.string().optional().nullable(),
  stage: z.enum([
    "NEW",
    "CONTACTED",
    "QUALIFIED",
    "VIEWING",
    "TEST_DRIVE",
    "NEGOTIATION",
    "RESERVED",
    "SOLD",
    "LOST",
  ]).default("NEW"),
  probability: z.coerce.number().min(0).max(100).optional().nullable(),
  notes: z.string().optional().nullable(),
  nextFollowUpAt: z.string().optional().nullable(),
  lostReason: z.string().optional().nullable(),
});
